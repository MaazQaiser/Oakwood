import { vehicleCardImage } from "@/lib/media/stock";
import { buildVehicleSlug } from "@/lib/vehicles/slug";
import type { Vehicle } from "@/types/vehicle";

function createVehicle(
  vehicle: Omit<Vehicle, "slug"> & { slug?: string },
): Vehicle {
  const slug =
    vehicle.slug ??
    buildVehicleSlug({
      makeSlug: vehicle.makeSlug,
      modelSlug: vehicle.modelSlug,
      locationSlug: vehicle.locationSlug,
      regionSlug: vehicle.regionSlug,
      stockId: vehicle.stockId,
    });

  return {
    ...vehicle,
    slug,
    image:
      vehicle.image ??
      vehicleCardImage({
        stockId: vehicle.stockId,
        bodyStyle: vehicle.bodyStyle,
        category: vehicle.category,
      }),
  };
}

